#!/usr/bin/env python3
"""Generate src/alwan/data/alwan_data_registry_gen.c from the table registry.

Reads every ALWAN_TABLE_EXTERN* line of data/alwan_data_tables.h with the switch
that guards it, and the switch's default in data/alwan_data_tables_config.h to
find its group. Writes, for each switchable table:

  - with ALWAN_EMBED_DATA=0, the pointer the readers index (NULL until
    alwan_data_load fills it);
  - in every build, one entry of alwan__table_registry: name, group, extent and
    the table's address (the array when embedded, the pointer when not), which
    is what alwan_data_pack_write, alwan_data_load and alwan_data_free walk.

ALWAN_TABLE_EXTERN_EMBEDDED tables are left out: every build embeds them.

Usage: python gen_table_registry.py [--check]
--check writes nothing and exits 1 when the committed file is out of date.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "alwan", "data")
HEADER = os.path.join(ROOT, "alwan_data_tables.h")
CONFIG = os.path.join(ROOT, "alwan_data_tables_config.h")
OUT = os.path.join(ROOT, "alwan_data_registry_gen.c")
OUT_H = os.path.join(ROOT, "alwan_data_registry_gen.h")

GROUPS = {
    "ALWAN_TABLES_AGX": "ALWAN_DATA_GROUP_AGX",
    "ALWAN_TABLES_SPECTRAL": "ALWAN_DATA_GROUP_SPECTRAL",
    "ALWAN_TABLES_SPD": "ALWAN_DATA_GROUP_SPD",
    "ALWAN_TABLES_QUALITY": "ALWAN_DATA_GROUP_QUALITY",
    "ALWAN_TABLES_CAMERAS": "ALWAN_DATA_GROUP_CAMERAS",
    "ALWAN_TABLES_LIGHT_SOURCES": "ALWAN_DATA_GROUP_LIGHT_SOURCES",
    "ALWAN_TABLES_FILM": "ALWAN_DATA_GROUP_FILM",
    "(!ALWAN_DATA_TABLES_MINIMAL)": "ALWAN_DATA_GROUP_OTHER",
}

# The refractiveindex.info arrays: outside the float-coordinate registry (read by
# binary search), and their extents come from the generated CSVs, so they are
# counted here and written to data/alwan_data_refractive_extents.h, which the
# definitions use too: a CSV that outgrows its extent fails to compile.
REFRACTIVE = [
    ("alwan__rx_lambda", "F32", "refractive/refractive_lambda.csv", "ALWAN__RX_LAMBDA_SIZE"),
    ("alwan__rx_values", "F32", "refractive/refractive_values.csv", "ALWAN__RX_VALUES_SIZE"),
    ("alwan__rx_coeffs", "F64", "refractive/refractive_coeffs.csv", "ALWAN__RX_COEFFS_SIZE"),
]
EXTENTS = os.path.join(ROOT, "alwan_data_refractive_extents.h")


def csv_count(rel):
    s = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return sum(1 for t in s.split(",") if t.strip())


def render_extents():
    o = ["/*",
         " * Alwan - Pure C colour science library",
         " * Copyright (c) 2025 Soufiane KHIAT",
         " * SPDX-License-Identifier: MIT",
         " *",
         " * GENERATED by tools/gen_table_registry.py from data/refractive/*.csv. Do not edit:",
         " * re-run the script after regenerating the refractive tables.",
         " */",
         "",
         "#ifndef ALWAN_DATA_REFRACTIVE_EXTENTS_H",
         "#define ALWAN_DATA_REFRACTIVE_EXTENTS_H",
         "",
         "enum {"]
    for i, (sym, kind, csv, enum) in enumerate(REFRACTIVE):
        o.append("    %s = %d%s" % (enum, csv_count(csv), "," if i + 1 < len(REFRACTIVE) else ""))
    o += ["};", "", "#endif /* ALWAN_DATA_REFRACTIVE_EXTENTS_H */", ""]
    return "\n".join(o)


def tables():
    defaults = dict(re.findall(r"#\s*define (ALWAN_TABLE_\w+) (.+)", open(CONFIG).read()))
    stack, out = [], []
    for line in open(HEADER, encoding="utf-8"):
        line = line.rstrip()
        m = re.match(r"#\s*if\s+(.*)", line)
        if m:
            stack.append(m.group(1).strip())
            continue
        if re.match(r"#\s*ifn?def", line):
            stack.append("")
            continue
        if re.match(r"#\s*endif", line):
            stack.pop()
            continue
        m = re.match(r"(ALWAN_TABLE_EXTERN\w*)\((alwan_table_\w+),\s*(\w+)\)$", line)
        if not m:
            continue
        macro, name, extent = m.groups()
        if macro == "ALWAN_TABLE_EXTERN_EMBEDDED":
            continue
        switch = [s for s in stack if s.startswith("ALWAN_TABLE_")]
        if len(switch) != 1:
            sys.exit("%s: expected one ALWAN_TABLE_ switch around it, found %r" % (name, switch))
        group = GROUPS.get(defaults.get(switch[0], ""))
        if not group:
            sys.exit("%s: switch %s has no group default" % (name, switch[0]))
        kind = {"ALWAN_TABLE_EXTERN": "DUAL", "ALWAN_TABLE_EXTERN_F32_ONLY": "F32",
                "ALWAN_TABLE_EXTERN_F64_ONLY": "F64"}[macro]
        out.append((name, extent, switch[0], group, kind))
    return out


def slots(ts):
    """(guard, f32-of-a-dual, C type, public symbol) for every runtime pointer."""
    out = []
    for sym, kind, csv, enum in REFRACTIVE:
        out.append(("ALWAN_WITH_REFRACTIVE_DATA", False, "alwan_f32" if kind == "F32" else "alwan_f64", sym))
    for name, extent, sw, group, kind in ts:
        if kind in ("DUAL", "F32"):
            out.append((sw, kind == "DUAL", "alwan_f32", name + "_f32"))
        if kind in ("DUAL", "F64"):
            out.append((sw, False, "alwan_f64", name + "_f64"))
    return out


def render_header(ts):
    o = ["/*",
         " * Alwan - Pure C colour science library",
         " * Copyright (c) 2025 Soufiane KHIAT",
         " * SPDX-License-Identifier: MIT",
         " *",
         " * GENERATED by tools/gen_table_registry.py. Do not edit: re-run the script.",
         " *",
         " * ALWAN_EMBED_DATA=0 only, included by data/alwan_data_tables.h: each switchable",
         " * table's hidden slot, and its name as a macro that loads it on first use.",
         " */",
         "",
         "#ifndef ALWAN_DATA_REGISTRY_GEN_H",
         "#define ALWAN_DATA_REGISTRY_GEN_H",
         ""]
    for guard, wrap, ctype, sym in slots(ts):
        o.append("#if %s" % guard)
        if wrap:
            o.append("#if ALWAN_WITH_F32")
        o.append("extern %s const *%s__slot;" % (ctype, sym))
        o.append("#define %s ALWAN__DEMAND_%s(%s__slot)" % (sym, "F32" if ctype == "alwan_f32" else "F64", sym))
        if wrap:
            o.append("#endif")
        o.append("#endif")
    o += ["", "#endif /* ALWAN_DATA_REGISTRY_GEN_H */", ""]
    return "\n".join(o)


def render(ts):
    o = []
    w = o.append
    w("/*")
    w(" * Alwan - Pure C colour science library")
    w(" * Copyright (c) 2025 Soufiane KHIAT")
    w(" * SPDX-License-Identifier: MIT")
    w(" *")
    w(" * GENERATED by tools/gen_table_registry.py from data/alwan_data_tables.h and")
    w(" * data/alwan_data_tables_config.h. Do not edit: re-run the script.")
    w(" *")
    w(" * %d switchable tables. With ALWAN_EMBED_DATA=0 the first half defines the" % len(ts))
    w(" * pointers the readers index; the registry below is in every build.")
    w(" */")
    w("")
    w('#include "../alwan.h"')
    w('#include "../alwan_internal.h"')
    w('#include "alwan_data_tables.h"')
    w('#include "alwan_data_registry.h"')
    w('#include "alwan_data_refractive.h"')
    w("")
    w("#if !ALWAN_EMBED_DATA")
    for guard, wrap, ctype, sym in slots(ts):
        w("#if %s" % guard)
        if wrap:
            w("#if ALWAN_WITH_F32")
        w("%s const *%s__slot = NULL;" % (ctype, sym))
        if wrap:
            w("#endif")
        w("#endif")
    w("#endif /* !ALWAN_EMBED_DATA */")
    w("")
    w("alwan__table_entry alwan__table_registry[] = {")
    for name, extent, sw, group, kind in ts:
        f32 = {"DUAL": "ALWAN__REG_DUAL_F32", "F32": "ALWAN__REG_F32", "F64": "ALWAN__REG_NONE"}[kind]
        f64 = {"DUAL": "ALWAN__REG_F64", "F32": "ALWAN__REG_NONE", "F64": "ALWAN__REG_F64"}[kind]
        w("#if %s" % sw)
        w('    { "%s", %s, %s, %s(%s), %s(%s) },' % (name, group, extent, f32, name, f64, name))
        w("#endif")
    w("#if ALWAN_WITH_REFRACTIVE_DATA")
    for sym, kind, csv, enum in REFRACTIVE:
        p32 = "ALWAN__REG_PLAIN(%s)" % sym if kind == "F32" else "NULL"
        p64 = "ALWAN__REG_PLAIN(%s)" % sym if kind == "F64" else "NULL"
        w('    { "%s", ALWAN_DATA_GROUP_REFRACTIVE, %s, %s, %s },' % (sym, enum, p32, p64))
    w("#endif")
    w("    { NULL, 0, 0, NULL, NULL }")
    w("};")
    w("")
    w("size_t const alwan__table_registry_count =")
    w("    sizeof(alwan__table_registry) / sizeof(alwan__table_registry[0]) - 1;")
    return "\n".join(o) + "\n"


def main():
    ts = tables()
    outputs = [(OUT, render(ts)), (OUT_H, render_header(ts)), (EXTENTS, render_extents())]
    if "--check" in sys.argv:
        stale = 0
        for path, text in outputs:
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if cur != text:
                print("%s is out of date: run tools/gen_table_registry.py" % os.path.basename(path))
                stale = 1
        return stale
    for path, text in outputs:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
