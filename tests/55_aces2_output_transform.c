static int test_output_transform_basic_rec709(void) {
    TEST_START("ACES 2.0 Output Transform - Rec.709 100 nits basic");

    alwan_rgb_f64 rgb_in = {ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18)};  /* 18% gray */
    alwan_rgb_f64 rgb_out;

    int status = alwan_aces2_output_transform_f64(&rgb_out, &rgb_in, ALWAN_ACES2_OUT_REC709_100NIT_BT1886);
    if (status != ALWAN_OK) {
        TEST_FAIL("Transform failed with error %d", status);
    }

    /* 18% gray should map to ~0.4-0.5 in display-encoded space */
    if (rgb_out.r < ALWAN_LITERAL(0.3) || rgb_out.r > ALWAN_LITERAL(0.6)) {
        TEST_FAIL("18%% gray mapped to unexpected value: %g", rgb_out.r);
    }

    /* Neutral input should produce neutral output */
    TEST_CHECK_NEAR(rgb_out.r, rgb_out.g, ALWAN_TEST_TOLERANCE);
    TEST_CHECK_NEAR(rgb_out.g, rgb_out.b, ALWAN_TEST_TOLERANCE);

    TEST_PASS_MSG();
    return 0;
}

