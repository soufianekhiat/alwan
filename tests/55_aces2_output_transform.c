static int test_output_transform_cinema_dcdm(void) {
    TEST_START("ACES 2.0 Output Transform - DCDM 48 nits");

    /* DCDM outputs X'Y'Z' (gamma 2.6 encoded XYZ for cinema projection) */
    alwan_rgb_f64 rgb_in = {ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18)};
    alwan_rgb_f64 rgb_out;

    int status = alwan_aces2_output_transform_f64(&rgb_out, &rgb_in, ALWAN_ACES2_OUT_DCDM_48NIT);
    if (status != ALWAN_OK) {
        TEST_FAIL("DCDM transform failed with error %d", status);
    }

    /* Check output is not NaN */
    if (rgb_out.r != rgb_out.r || rgb_out.g != rgb_out.g || rgb_out.b != rgb_out.b) {
        TEST_FAIL("DCDM produced NaN: (%g, %g, %g)", rgb_out.r, rgb_out.g, rgb_out.b);
    }

    /* For neutral gray, Y' should be in reasonable range for gamma 2.6 encoded cinema */
    /* Y component (green channel in XYZ output) should be ~0.3-0.6 for 18% gray */
    if (rgb_out.g < ALWAN_LITERAL(0.2) || rgb_out.g > ALWAN_LITERAL(0.7)) {
        TEST_FAIL("DCDM Y' value out of expected range: %g (expected 0.2-0.7)", rgb_out.g);
    }

    printf("    DCDM output (X'Y'Z'): (%g, %g, %g)\n", rgb_out.r, rgb_out.g, rgb_out.b);

    TEST_PASS_MSG();
    return 0;
}

static int test_output_transform_cinema_p3dci(void) {
    TEST_START("ACES 2.0 Output Transform - P3-DCI 48 nits");

    /* P3-DCI outputs P3 primaries with gamma 2.6 encoding for cinema */
    alwan_rgb_f64 rgb_in = {ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18), ALWAN_LITERAL(0.18)};
    alwan_rgb_f64 rgb_out;

    int status = alwan_aces2_output_transform_f64(&rgb_out, &rgb_in, ALWAN_ACES2_OUT_P3DCI_48NIT);
    if (status != ALWAN_OK) {
        TEST_FAIL("P3-DCI transform failed with error %d", status);
    }

    /* Check output is not NaN */
    if (rgb_out.r != rgb_out.r || rgb_out.g != rgb_out.g || rgb_out.b != rgb_out.b) {
        TEST_FAIL("P3-DCI produced NaN: (%g, %g, %g)", rgb_out.r, rgb_out.g, rgb_out.b);
    }

    /* For neutral gray, all channels should be similar (achromatic) */
    alwan_f64 max_diff = ALWAN_ABS(rgb_out.r - rgb_out.g);
    alwan_f64 diff_gb = ALWAN_ABS(rgb_out.g - rgb_out.b);
    alwan_f64 diff_rb = ALWAN_ABS(rgb_out.r - rgb_out.b);
    if (diff_gb > max_diff) max_diff = diff_gb;
    if (diff_rb > max_diff) max_diff = diff_rb;

    if (max_diff > 0.05) {
        TEST_FAIL("P3-DCI neutral gray not achromatic: (%g, %g, %g), max diff: %g",
                  rgb_out.r, rgb_out.g, rgb_out.b, max_diff);
    }

    /* Output should be in reasonable range for gamma 2.6 encoded cinema */
    if (rgb_out.g < ALWAN_LITERAL(0.2) || rgb_out.g > ALWAN_LITERAL(0.7)) {
        TEST_FAIL("P3-DCI value out of expected range: %g (expected 0.2-0.7)", rgb_out.g);
    }

    printf("    P3-DCI output (gamma 2.6): (%g, %g, %g)\n", rgb_out.r, rgb_out.g, rgb_out.b);

    TEST_PASS_MSG();
    return 0;
}

